const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const crypto=require('node:crypto');
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'nexus-test-'));
process.env.NEXUS_DB_FILE=path.join(temp,'test.sqlite');
process.env.NEXUS_DEMO_PASSWORD='NexusDemo!2026';
process.env.RAZORPAY_TEST_KEY_ID='rzp_test_local';
process.env.RAZORPAY_TEST_KEY_SECRET='local_secret';
process.env.RAZORPAY_WEBHOOK_SECRET='local_webhook_test';
const {server,db}=require('./index.cjs');
let base;
const call=async(route,method='GET',body,cookie='')=>{const r=await fetch(base+'/api'+route,{method,headers:{...(body?{'content-type':'application/json'}:{}),...(cookie?{cookie}:{})},body:body?JSON.stringify(body):undefined});return {status:r.status,data:await r.json(),cookie:r.headers.get('set-cookie')?.split(';')[0]};};
const webhook=async(event,eventId)=>{const raw=JSON.stringify(event),signature=crypto.createHmac('sha256',process.env.RAZORPAY_WEBHOOK_SECRET).update(raw).digest('hex');return fetch(base+'/api/razorpay/webhook',{method:'POST',headers:{'x-razorpay-signature':signature,'x-razorpay-event-id':eventId},body:raw});};
test('single Nexus account buys and manages subscriptions directly',async()=>{
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  base=`http://127.0.0.1:${server.address().port}`;
  const networkFetch=global.fetch;
  const providerCalls=[];
  let lastSubscriptionNotes={};
  let createdSubscriptions=0;
  const subscriptionNotes=new Map();
  global.fetch=(url,options={})=>{
    if(!String(url).startsWith('https://api.razorpay.com/'))return networkFetch(url,options);
    providerCalls.push({url:String(url),method:options.method,body:options.body?JSON.parse(options.body):null});
    let result;
    if(String(url).endsWith('/plans/plan_teststarter'))result={id:'plan_teststarter',period:'monthly',interval:1,item:{currency:'INR',amount:199900}};
    else if(String(url).endsWith('/plans/plan_testgrowth'))result={id:'plan_testgrowth',period:'monthly',interval:1,item:{currency:'INR',amount:599900}};
    else if(options.method==='GET'){const providerId=String(url).split('/').at(-1);result={id:providerId,status:'created',short_url:'https://rzp.io/rzp/test',notes:subscriptionNotes.get(providerId)||lastSubscriptionNotes};}
    else {if(String(url).endsWith('/subscriptions')){lastSubscriptionNotes=JSON.parse(options.body).notes;createdSubscriptions++;subscriptionNotes.set(createdSubscriptions===1?'sub_rzp_new':`sub_rzp_new${createdSubscriptions}`,lastSubscriptionNotes);}result={id:createdSubscriptions===1?'sub_rzp_new':`sub_rzp_new${createdSubscriptions}`,status:'created',short_url:'https://rzp.io/rzp/test'};}
    return Promise.resolve(new Response(JSON.stringify(result),{status:200,headers:{'content-type':'application/json'}}));
  };
  try{
    const nexus=await call('/login','POST',{email:'nexus@nexus.demo',password:'NexusDemo!2026'});
    assert.equal(nexus.status,200);
    assert.equal((await call('/login','POST',{email:'operator@nexus.demo',password:'NexusDemo!2026'})).status,401);
    assert.equal((await call('/login','POST',{email:'buyer@nexus.demo',password:'NexusDemo!2026'})).status,401);
    assert.equal((await call('/requests','POST',{kind:'subscribe',plan_id:'starter'},nexus.cookie)).status,410);
    assert.equal((await call('/subscriptions/checkout','POST',{plan_id:'starter'},nexus.cookie)).status,409);
    assert.equal((await call('/plans/starter/razorpay-plan','POST',{razorpay_plan_id:'plan_teststarter'},nexus.cookie)).status,200);
    assert.equal((await call('/plans/growth/razorpay-plan','POST',{razorpay_plan_id:'plan_testgrowth'},nexus.cookie)).status,200);
    const checkout=await call('/subscriptions/checkout','POST',{plan_id:'starter'},nexus.cookie);
    assert.equal(checkout.status,201);assert.equal(checkout.data.url,'https://rzp.io/rzp/test');
    const creation=providerCalls.find(x=>x.url.endsWith('/subscriptions')&&x.method==='POST').body;
    assert.equal(creation.addons[0].item.amount,199900);
    assert.equal(creation.addons[0].item.currency,'INR');
    assert.ok(creation.start_at>Math.floor(Date.now()/1000)+29*86400);
    const subId=checkout.data.subscription_id;
    const retry=await call('/subscriptions/checkout','POST',{plan_id:'starter'},nexus.cookie);
    assert.equal(retry.status,200);assert.equal(retry.data.reused,true);
    assert.equal(providerCalls.filter(x=>x.url.endsWith('/subscriptions')&&x.method==='POST').length,1);
    const upgrade=await call(`/subscriptions/${subId}/change`,'POST',{plan_id:'growth'},nexus.cookie);
    assert.equal(upgrade.status,200);assert.equal(upgrade.data.schedule,'now');
    assert.equal(providerCalls.at(-1).body.schedule_change_at,'now');
    const activated={event:'subscription.activated',payload:{subscription:{entity:{id:'sub_rzp_new',status:'active',plan_id:'plan_testgrowth',current_end:1790000000}}}};
    assert.equal((await webhook(activated,'evt_active')).status,200);
    const duplicate=await webhook(activated,'evt_active');assert.equal(duplicate.status,200);assert.equal((await duplicate.json()).duplicate,true);
    const downgrade=await call(`/subscriptions/${subId}/change`,'POST',{plan_id:'starter'},nexus.cookie);
    assert.equal(downgrade.status,200);assert.equal(downgrade.data.schedule,'cycle_end');
    assert.equal(providerCalls.at(-1).body.schedule_change_at,'cycle_end');
    const cancel=await call(`/subscriptions/${subId}/cancel`,'POST',null,nexus.cookie);
    assert.equal(cancel.status,200);assert.equal(providerCalls.at(-1).body.cancel_at_cycle_end,false);
    const charge={event:'subscription.charged',payload:{subscription:{entity:{id:'sub_rzp_new',status:'active',current_end:1790000000}},payment:{entity:{id:'pay_test',invoice_id:'inv_test',amount:199900}}}};
    assert.equal((await webhook(charge,'evt_charge')).status,200);
    const invoices=await call('/invoices','GET',null,nexus.cookie);
    assert.equal(invoices.status,200);assert.equal(invoices.data.invoices.find(x=>x.provider_invoice_id==='inv_test').status,'paid');
    const audit=await call('/audit','GET',null,nexus.cookie);assert.equal(audit.status,200);
    assert.ok(audit.data.audit.some(x=>x.action==='billing.cancellation_submitted'));
    const cancelled={event:'subscription.cancelled',payload:{subscription:{entity:{id:'sub_rzp_new',status:'cancelled'}}}};
    assert.equal((await webhook(cancelled,'evt_cancelled')).status,200);
    const publicPlans=await call('/public/plans');
    assert.equal(publicPlans.status,200);
    assert.deepEqual(publicPlans.data.plans.map(plan=>plan.id),['starter','growth']);
    const pending=await call('/public/subscriptions/checkout','POST',{plan_id:'starter'});
    assert.equal(pending.status,201);
    const replacement=await call('/public/subscriptions/checkout','POST',{plan_id:'growth'});
    assert.equal(replacement.status,201);
    assert.notEqual(replacement.data.subscription_id,pending.data.subscription_id);
    assert.equal(db.prepare('SELECT status FROM subscriptions WHERE id=?').get(pending.data.subscription_id).status,'canceled');
    assert.equal(db.prepare('SELECT plan_id FROM subscriptions WHERE id=?').get(replacement.data.subscription_id).plan_id,'growth');
    assert.ok(providerCalls.some(x=>x.url.endsWith('/subscriptions/sub_rzp_new2/cancel')&&x.body?.cancel_at_cycle_end===false));
  }finally{
    global.fetch=networkFetch;
    await new Promise(resolve=>server.close(resolve));db.close();fs.rmSync(temp,{recursive:true,force:true});
  }
});
